#!/usr/bin/env bash

set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
AWS_KUBE_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"

PROVISION_DIR="${PROVISION_DIR:-$AWS_KUBE_DIR/provision}"
K8S_DIR="${K8S_DIR:-$AWS_KUBE_DIR/k8s}"
RUNTIME_VALUES_FILE="${RUNTIME_VALUES_FILE:-$K8S_DIR/runtime-values.env}"
TOFU_BIN="${TOFU_BIN:-tofu}"

usage() {
  printf '%s\n' \
    'Usage: update-runtime-values.sh [--check]' \
    '' \
    'Read OpenTofu outputs and synchronize generated runtime values into Kubernetes YAML.' \
    '' \
    'Options:' \
    '  --check  Fail if runtime-values.env or any YAML file is out of sync.' \
    '  -h       Show this help.'
}

mode="update"
case "${1:-}" in
  "")
    ;;
  --check)
    mode="check"
    ;;
  -h|--help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac

if ! command -v "$TOFU_BIN" >/dev/null 2>&1; then
  printf 'OpenTofu executable not found: %s\n' "$TOFU_BIN" >&2
  exit 1
fi

if ! command -v perl >/dev/null 2>&1; then
  printf 'perl is required to synchronize YAML values.\n' >&2
  exit 1
fi

target_group_arn="$(cd "$PROVISION_DIR" && "$TOFU_BIN" output -raw traefik_target_group_arn)"
external_secret_name="$(cd "$PROVISION_DIR" && "$TOFU_BIN" output -raw external_secret_name)"

if [[ ! "$target_group_arn" =~ ^arn:aws:elasticloadbalancing:[^:]+:[0-9]{12}:targetgroup/[^/]+/[A-Za-z0-9]+$ ]]; then
  printf 'Unexpected traefik_target_group_arn output: %s\n' "$target_group_arn" >&2
  exit 1
fi

if [[ ! "$external_secret_name" =~ ^[A-Za-z0-9/_+=.@-]+$ ]]; then
  printf 'Unexpected external_secret_name output: %s\n' "$external_secret_name" >&2
  exit 1
fi

printf 'traefik_target_group_arn=%s\n' "$target_group_arn"
printf 'external_secret_name=%s\n' "$external_secret_name"

tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/aws-kube-runtime-values.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT

rewrite_script="$tmp_dir/rewrite-yaml.pl"
cat >"$rewrite_script" <<'PERL'
use strict;
use warnings;

my $target_group_arn = $ENV{TARGET_GROUP_ARN}
    // die "TARGET_GROUP_ARN is not set\n";
my $external_secret_name = $ENV{EXTERNAL_SECRET_NAME}
    // die "EXTERNAL_SECRET_NAME is not set\n";

while (<>) {
    # platform/apps/values.yaml stores the ARN under targetGroup.arn.
    if ($ARGV =~ m{(?:^|/)platform/apps/values\.yaml$}) {
        s{^(\s*arn:\s*)(["']?)arn:aws:elasticloadbalancing:[^:"'\s]+:\d{12}:targetgroup/[^/"'\s]+/[A-Za-z0-9]+}{$1 . $2 . $target_group_arn}e;
    }

    # Helm-rendered TargetGroupBinding manifests.
    s{^(\s*targetGroupARN:\s*)(["']?)arn:aws:elasticloadbalancing:[^:"'\s]+:\d{12}:targetgroup/[^/"'\s]+/[A-Za-z0-9]+}{$1 . $2 . $target_group_arn}e;

    # ExternalSecret remoteRef.key values, including flow-style YAML mappings.
    s{(\bkey:\s*)(["']?)[^"'\s,\}]+/external-secrets/[^"'\s,\}]+}{$1 . $2 . $external_secret_name}ge;

    print;
}
PERL

expected_runtime_file="$tmp_dir/runtime-values.env"
{
  printf '# Generated by aws_kube/scripts/update-runtime-values.sh.\n'
  printf '# Source this file when commands need the current provisioned values.\n'
  printf 'TRAEFIK_TARGET_GROUP_ARN=%q\n' "$target_group_arn"
  printf 'EXTERNAL_SECRET_NAME=%q\n' "$external_secret_name"
} >"$expected_runtime_file"

yaml_files=()
while IFS= read -r -d '' file; do
  yaml_files+=("$file")
done < <(
  find "$K8S_DIR" -type f \( -name '*.yaml' -o -name '*.yml' \) \
    ! -path "$K8S_DIR/platform/core/charts/*" -print0
)

if [[ ${#yaml_files[@]} -eq 0 ]]; then
  printf 'No YAML files found under %s\n' "$K8S_DIR" >&2
  exit 1
fi

changed_yaml=()
for index in "${!yaml_files[@]}"; do
  file="${yaml_files[$index]}"
  rendered_file="$tmp_dir/yaml-$index"

  TARGET_GROUP_ARN="$target_group_arn" \
    EXTERNAL_SECRET_NAME="$external_secret_name" \
    perl "$rewrite_script" "$file" >"$rendered_file"

  if ! cmp -s "$file" "$rendered_file"; then
    changed_yaml+=("$file")
  fi
done

runtime_file_changed=false
if [[ ! -f "$RUNTIME_VALUES_FILE" ]] || ! cmp -s "$RUNTIME_VALUES_FILE" "$expected_runtime_file"; then
  runtime_file_changed=true
fi

if [[ "$mode" == "check" ]]; then
  failed=false

  if [[ "$runtime_file_changed" == true ]]; then
    printf 'Out of sync: %s\n' "$RUNTIME_VALUES_FILE" >&2
    failed=true
  fi

  for file in "${changed_yaml[@]}"; do
    printf 'Out of sync: %s\n' "$file" >&2
    failed=true
  done

  if [[ "$failed" == true ]]; then
    printf 'Run %s to update generated runtime values.\n' "$0" >&2
    exit 1
  fi

  printf 'Runtime values are in sync.\n'
  exit 0
fi

for index in "${!yaml_files[@]}"; do
  file="${yaml_files[$index]}"
  rendered_file="$tmp_dir/yaml-$index"

  if cmp -s "$file" "$rendered_file"; then
    continue
  fi

  chmod "$(stat -c '%a' "$file")" "$rendered_file"
  mv "$rendered_file" "$file"
done

if [[ "$runtime_file_changed" == true ]]; then
  chmod 0644 "$expected_runtime_file"
  mv "$expected_runtime_file" "$RUNTIME_VALUES_FILE"
fi

if [[ ${#changed_yaml[@]} -eq 0 && "$runtime_file_changed" == false ]]; then
  printf 'Runtime values are already in sync.\n'
else
  printf 'Updated %d YAML file(s).\n' "${#changed_yaml[@]}"
  for file in "${changed_yaml[@]}"; do
    printf '  %s\n' "$file"
  done
  if [[ "$runtime_file_changed" == true ]]; then
    printf '  %s\n' "$RUNTIME_VALUES_FILE"
  fi
fi
